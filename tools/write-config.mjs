// Writes public/js/config.js from environment variables.
//   Vercel: runs as the build command, reading the project's Environment Variables.
//   Local:  `node tools/write-config.mjs` reads .env.local (see .env.example).
// Only the Supabase URL and the publishable (public) key may go to the browser.
// The script refuses secret or service-role keys so they can never be published.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

function readDotEnv(file) {
  if (!existsSync(file)) return {};
  const values = {};
  for (const line of readFileSync(file, 'utf8').split(/\r?\n/)) {
    const match = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
    if (match && !line.trimStart().startsWith('#')) values[match[1]] = match[2].replace(/^(['"])(.*)\1$/, '$2');
  }
  return values;
}

const env = { ...readDotEnv(join(root, '.env.local')), ...process.env };
const url = (env.SUPABASE_URL || '').trim();
const key = (env.SUPABASE_PUBLISHABLE_KEY || '').trim();

function fail(message) {
  console.error('write-config: ' + message);
  process.exit(1);
}

function jwtRole(token) {
  try {
    return JSON.parse(Buffer.from(token.split('.')[1], 'base64url').toString('utf8')).role;
  } catch {
    return undefined;
  }
}

let config = null;
if (url || key) {
  if (!url || !key) fail('set both SUPABASE_URL and SUPABASE_PUBLISHABLE_KEY, or neither.');
  if (!/^https:\/\/[a-z0-9-]+\.supabase\.co$|^https:\/\/[a-z0-9.-]+$/i.test(url)) fail('SUPABASE_URL must look like https://<project>.supabase.co');
  if (/^sb_secret_/.test(key)) fail('that is a SECRET key. Use the publishable key (sb_publishable_...).');
  const isPublishable = /^sb_publishable_[A-Za-z0-9_-]+$/.test(key);
  const isLegacyAnon = key.split('.').length === 3 && jwtRole(key) === 'anon';
  if (!isPublishable && !isLegacyAnon) fail('SUPABASE_PUBLISHABLE_KEY must be the publishable key (sb_publishable_...) or the legacy anon key. Never the service_role key.');
  config = { supabaseUrl: url, supabaseKey: key };
} else {
  console.warn('write-config: no Supabase settings found, the site will run as a local preview.');
}

const output = '// Generated by tools/write-config.mjs. Do not edit; do not commit.\n' +
  'window.PIECENOA_CONFIG = ' + (config ? 'Object.freeze(' + JSON.stringify(config) + ')' : 'null') + ';\n';
writeFileSync(join(root, 'public', 'js', 'config.js'), output);
console.log('write-config: wrote public/js/config.js (' + (config ? 'Supabase ' + new URL(url).host : 'preview mode') + ')');
